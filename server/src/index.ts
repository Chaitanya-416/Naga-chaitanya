import { createApp } from './app.js';
import { config } from './config/index.js';

const app = createApp();

const server = app.listen(config.port, () => {
  console.log(`🛡️  ScopeSeal AI Gateway running on port ${config.port} [${config.nodeEnv}]`);
  console.log(`🔒 Zero-Trust Policy Engine & Firewall initialized`);
});

process.on('SIGTERM', () => {
  console.log('SIGTERM received. Shutting down gracefully...');
  server.close(() => {
    console.log('Server closed.');
    process.exit(0);
  });
});
